STEEL = 7850  # плотность стали, кг/м³


def rod_kg_m(d_mm):
    """Круг, арматура (по номинальному диаметру): 0,00617·d², кг/м."""
    return 0.0061654 * d_mm ** 2


def square_kg_m(a_mm):
    return STEEL * (a_mm / 1000) ** 2


def strip_kg_m(a_mm, b_mm):
    return STEEL * a_mm * b_mm / 1e6


def round_pipe_kg_m(d_mm, s_mm):
    """Круглая труба: 0,02466·s·(D−s), кг/м (ГОСТ 10704, 3262 — теоретическая масса)."""
    return 0.0246615 * s_mm * (d_mm - s_mm)


def prof_pipe_kg_m(a_mm, b_mm, s_mm):
    """Профильная труба по формуле ГОСТ 8639/8645 со скруглёнными углами (радиус ≈ 1,5–2s), кг/м."""
    return 0.0157 * s_mm * (a_mm + b_mm - 2.86 * s_mm)


def sheet_kg_m2(t_mm):
    return STEEL * t_mm / 1000


def fmt(x, nd=2):
    return f"{x:.{nd}f}".replace(".", ",")


def per_tonne(kg_m):
    return f"{1000 / kg_m:.0f}"


